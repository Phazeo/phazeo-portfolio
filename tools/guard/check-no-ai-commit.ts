#!/usr/bin/env node
/**
 * Block AI attribution in commits - not human emails.
 *
 * Community pattern (2026): Cursor/Claude/Copilot inject Co-authored-by /
 * Made-with / Generated-with trailers and sometimes use tool emails
 * (e.g. cursoragent@cursor.com). A commit-msg hook + CI refuse those;
 * any normal user email as author is fine.
 *
 * Usage:
 *   node tools/guard/check-no-ai-commit.ts .git/COMMIT_EDITMSG
 *   node tools/guard/check-no-ai-commit.ts --range origin/main..HEAD
 *   node tools/guard/check-no-ai-commit.ts --authors origin/main..HEAD
 */
import { spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";

/** AI-only message patterns. Human Co-authored-by is allowed. */
const MESSAGE_PATTERNS: ReadonlyArray<readonly [RegExp, string]> = [
  [
    /^\s*co-authored-by\s*:.*(cursor|cursoragent|copilot|chatgpt|claude|anthropic|gemini)/im,
    "AI Co-authored-by trailer",
  ],
  [/^\s*made-with\s*:\s*(cursor|claude|copilot|chatgpt)/im, "AI Made-with trailer"],
  [/^\s*generated-by\s*:\s*(cursor|claude|copilot|chatgpt)/im, "AI Generated-by trailer"],
  [/^\s*claude-session\s*:/im, "Claude-Session trailer"],
  [/cursoragent@cursor\.com/i, "Cursor agent email in message"],
  [/noreply@anthropic\.com/i, "Anthropic noreply email in message"],
  [/claude\.ai\//i, "claude.ai link"],
  [/claude\.com\/claude-code/i, "Claude Code link"],
  [/\u{1F916}\s*generated with/iu, "robot 'Generated with' line"],
  [/generated with\s*\[?\s*(claude|cursor|copilot|chatgpt)/i, "'Generated with <AI>' line"],
  [
    /\bgenerated by\s+(claude|chatgpt|copilot|gpt-|cursor|gemini)/i,
    "'Generated by <AI tool>' line",
  ],
];

/** Author/committer emails that are AI tools (human emails are fine). */
const AI_EMAIL_BLOCK: readonly RegExp[] = [
  /cursoragent@/i,
  /noreply@anthropic\.com/i,
  /copilot@/i,
  /chatgpt@/i,
  /claude@anthropic/i,
  /@cursor\.com$/i,
];

function withoutGitComments(text: string): string {
  const kept: string[] = [];
  for (const line of text.split(/\r?\n/)) {
    if (line.startsWith("# ") && line.includes(">8")) break;
    if (!line.startsWith("#")) kept.push(line);
  }
  return kept.join("\n");
}

function messageOffences(message: string): string[] {
  const found: string[] = [];
  for (const [pattern, label] of MESSAGE_PATTERNS) {
    if (pattern.test(message)) found.push(label);
  }
  return found;
}

function aiEmailLabel(email: string): string | null {
  for (const rx of AI_EMAIL_BLOCK) {
    if (rx.test(email)) return email;
  }
  return null;
}

function report(where: string, found: readonly string[]): void {
  console.error(`\n${where} has AI attribution (human emails are fine):`);
  for (const label of found) {
    console.error(`    - ${label}`);
  }
  console.error("Remove AI Co-authored-by / Made-with / tool emails and try again.");
}

function commitsInRange(revRange: string): Array<[string, string]> {
  const result = spawnSync("git", ["log", "--format=%H%x1f%B%x1e", revRange], {
    encoding: "utf8",
  });
  if (result.status !== 0) {
    console.error(result.stderr || `git log failed for range ${revRange}`);
    process.exit(1);
  }
  const commits: Array<[string, string]> = [];
  for (const chunk of result.stdout.split("\x1e")) {
    if (!chunk.includes("\x1f")) continue;
    const [sha, body] = chunk.split("\x1f");
    if (sha?.trim()) commits.push([sha.trim(), body ?? ""]);
  }
  return commits;
}

/** Rows of: sha, author name, author email, committer name, committer email. */
function authorsInRange(revRange: string): Array<[string, string, string, string, string]> {
  const result = spawnSync(
    "git",
    ["log", "--format=%H%x1f%an%x1f%ae%x1f%cn%x1f%ce%x1e", revRange],
    { encoding: "utf8" }
  );
  if (result.status !== 0) {
    console.error(result.stderr || `git log failed for range ${revRange}`);
    process.exit(1);
  }
  const rows: Array<[string, string, string, string, string]> = [];
  for (const chunk of result.stdout.split("\x1e")) {
    if (!chunk.includes("\x1f")) continue;
    const [sha, an, ae, cn, ce] = chunk.split("\x1f");
    if (sha?.trim()) rows.push([sha.trim(), an ?? "", ae ?? "", cn ?? "", ce ?? ""]);
  }
  return rows;
}

function main(): void {
  const args = process.argv.slice(2);
  if (args.length === 0) {
    console.error(
      "Usage: check-no-ai-commit.ts <COMMIT_EDITMSG> | --range <rev> | --authors <rev>"
    );
    process.exit(1);
  }

  let failed = false;

  if (args[0] === "--authors") {
    const revRange = args[1];
    if (!revRange) {
      console.error("--authors needs a rev-range");
      process.exit(1);
    }
    const rows = authorsInRange(revRange);
    for (const [sha, an, ae, cn, ce] of rows) {
      const emails: Array<[string, string]> = [
        ["author", ae],
        ["committer", ce],
      ];
      for (const [who, email] of emails) {
        const bad = aiEmailLabel(email);
        if (bad) {
          console.error(
            `\ncommit ${sha.slice(0, 8)}: ${who} email is an AI tool (${email}), not a person`
          );
          failed = true;
        }
      }
      // Also block AI-looking names on author/committer
      const names: Array<[string, string]> = [
        ["author", an],
        ["committer", cn],
      ];
      for (const [who, name] of names) {
        if (/\b(cursor agent|copilot|chatgpt|claude code)\b/i.test(name)) {
          console.error(`\ncommit ${sha.slice(0, 8)}: ${who} name looks like an AI tool (${name})`);
          failed = true;
        }
      }
    }
  } else if (args[0] === "--range") {
    const revRange = args[1];
    if (!revRange) {
      console.error("--range needs a rev-range");
      process.exit(1);
    }
    const commits = commitsInRange(revRange);
    for (const [sha, message] of commits) {
      const found = messageOffences(message);
      if (found.length) {
        report(`commit ${sha.slice(0, 8)}`, found);
        failed = true;
      }
    }
  } else {
    const msgFile = args[0];
    if (!msgFile) process.exit(1);
    const message = withoutGitComments(readFileSync(msgFile, "utf8"));
    const found = messageOffences(message);
    if (found.length) {
      report("this commit message", found);
      failed = true;
    }
  }

  process.exit(failed ? 1 : 0);
}

main();
